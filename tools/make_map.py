"""
Builds src/maps.h – 128×64 land bitmaps for microHAMCLOCK.

Source: Natural Earth (public domain), https://github.com/nvkelso/natural-earth-vector
  geojson/ne_110m_land.geojson             – land (world, Europe)
  geojson/ne_10m_admin_0_countries.geojson – borders of Czechia

Usage:
    python tools/make_map.py ne_110m_land.geojson ne_10m_admin_0_countries.geojson [--preview dir]

The CZECHIA view doesn't draw land, only the territory of Czechia (borders from ne_10m_admin_0_countries).

Each view is a rectangle in geographic coordinates (parallels
and meridians are straight lines). Polygons are drawn at 8× scale
and a pixel is land when at least half of it is covered.
The firmware computes the coastline from the mask itself.
"""
import json
import math
import os
import sys

from PIL import Image, ImageDraw

W, H = 128, 64
SS = 8  # supersampling

# name, west, east, north, south (degrees), what is drawn
# Czechia: 4.7 km per pixel both ways, so the country isn't stretched.
VIEWS = [
    ("WORLD", -180.0, 180.0, 90.0, -90.0, "land"),
    ("EUROPE", -30.0, 50.0, 72.0, 30.0, "land"),
    ("CZECHIA", 11.3, 19.6, 51.15, 48.45, "CZE"),
]


def rings(geojson, country=None):
    for f in geojson["features"]:
        if country and f["properties"].get("ADM0_A3") != country:
            continue
        g = f["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in polys:
            yield poly[0]  # outer ring; the 110m data has no holes that would be visible


def mask(geojson, view):
    _, west, east, north, south, what = view
    img = Image.new("L", (W * SS, H * SS), 0)
    d = ImageDraw.Draw(img)
    sx = W * SS / (east - west)
    sy = H * SS / (north - south)
    for ring in rings(geojson, None if what == "land" else what):
        pts = [((lon - west) * sx, (north - lat) * sy) for lon, lat in ring]
        if len(pts) >= 3:
            d.polygon(pts, fill=255)
    small = img.resize((W, H), Image.BOX)
    return [[small.getpixel((x, y)) >= 128 for x in range(W)] for y in range(H)]


def to_c(name, m, view):
    _, west, east, north, south, _ = view
    out = [f"// {name}: lon {west}..{east}, lat {north}..{south}, rows of 16 bytes, MSB = left pixel"]
    out.append(f"static const MapView MAP_{name} = {{{west:.3f}f, {east:.3f}f, {north:.3f}f, {south:.3f}f, {{")
    for y in range(H):
        row = []
        for bx in range(W // 8):
            b = 0
            for i in range(8):
                b = b << 1 | m[y][bx * 8 + i]
            row.append(f"0x{b:02X}")
        out.append("  " + ",".join(row) + ",")
    out.append("}};")
    return "\n".join(out)


def preview(m, path, view, night):
    """4× enlarged preview: coastline and dotted night."""
    img = Image.new("RGB", (W * 4, H * 4), (0, 0, 0))
    d = ImageDraw.Draw(img)
    for y in range(H):
        for x in range(W):
            land = m[y][x]
            edge = land and any(
                not m[yy][xx % W]
                for xx, yy in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1))
                if 0 <= yy < H
            )
            on = edge
            if not on and night(view, x, y):
                on = (x + y) % 2 == 0 and y % 2 == 0
            if on:
                d.rectangle([x * 4, y * 4, x * 4 + 3, y * 4 + 3], fill=(140, 220, 255))
    img.save(path)


def make_night(hour_utc=18.0, decl=-6.0):
    sub_lon = (12.0 - hour_utc) * 15.0
    def night(view, x, y):
        _, west, east, north, south, _ = view
        lon = west + (x + 0.5) * (east - west) / W
        lat = north - (y + 0.5) * (north - south) / H
        r = math.radians
        alt = math.sin(r(lat)) * math.sin(r(decl)) + math.cos(r(lat)) * math.cos(r(decl)) * math.cos(r(lon - sub_lon))
        return alt < 0
    return night


def main():
    prev = sys.argv[sys.argv.index("--preview") + 1] if "--preview" in sys.argv else None
    sources = {}
    with open(sys.argv[1], encoding="utf-8") as f:
        sources["land"] = json.load(f)
    with open(sys.argv[2], encoding="utf-8") as f:
        sources["countries"] = json.load(f)

    parts = [
        "// Generated by tools/make_map.py from Natural Earth ne_110m_land and ne_10m_admin_0_countries (public domain).",
        "// Do not edit by hand.",
        "#pragma once",
        "",
        "struct MapView { float west, east, north, south; uint8_t bits[64][16]; };",
        "",
    ]
    for view in VIEWS:
        m = mask(sources["land" if view[5] == "land" else "countries"], view)
        parts.append(to_c(view[0], m, view))
        parts.append("")
        if prev:
            os.makedirs(prev, exist_ok=True)
            preview(m, os.path.join(prev, f"map_{view[0].lower()}.png"), view, make_night())

    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", "maps.h")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts))
    print("written", os.path.normpath(out))


if __name__ == "__main__":
    main()
