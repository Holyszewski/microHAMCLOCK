"""
Firmware version from git. A PlatformIO script (extra_scripts = pre:) that runs
before every build and writes src/fw_version.h (not in git).

Development build:  git describe, e.g. 0.5.1-3-g1a2b3c4 (3 commits after v0.5.1),
                    plus -dirty with uncommitted changes. On the OLED "0.5.1+3".
Release:            MICROHAMCLOCK_RELEASE=0.6.0 python -m platformio run
                    The number must match the first heading in CHANGELOG.md.
"""
import os
import re
import subprocess

Import("env")  # noqa: F821 (provided by PlatformIO)

ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
HEADER = os.path.join(ROOT, "src", "fw_version.h")


def fail(msg):
    print("version.py: " + msg)
    env.Exit(1)  # noqa: F821


def changelog_top():
    with open(os.path.join(ROOT, "CHANGELOG.md"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("## "):
                return line[3:].strip()
    return ""


def from_git():
    try:
        out = subprocess.run(["git", "describe", "--tags", "--match", "v[0-9]*", "--dirty"],
                             cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        print("version.py: git describe failed, version unknown")
        return "0.0.0-unknown", "0.0.0?"
    m = re.fullmatch(r"v(\d+\.\d+\.\d+)(?:-(\d+)-g[0-9a-f]+)?(-dirty)?", out)
    if not m:
        fail("unexpected git describe output: " + out)
    full = out[1:]
    short = m.group(1)
    if m.group(2):
        short += "+" + m.group(2)   # commits since the release
    elif m.group(3):
        short += "+"                # uncommitted changes right on a release
    return full, short


release = os.environ.get("MICROHAMCLOCK_RELEASE", "").strip()
if release:
    if not re.fullmatch(r"\d+\.\d+\.\d+", release):
        fail("MICROHAMCLOCK_RELEASE must be in the form X.Y.Z")
    if not changelog_top().startswith(release + " "):
        fail("the first heading in CHANGELOG.md is not version " + release)
    full = short = release
else:
    full, short = from_git()

text = ("// Generated by tools/version.py, do not edit.\n"
        '#define MICROHAMCLOCK_VERSION "%s"\n'
        '#define MICROHAMCLOCK_VERSION_OLED "%s"\n' % (full, short))
try:
    with open(HEADER, encoding="utf-8") as f:
        old = f.read()
except OSError:
    old = ""
if old != text:  # rewrite only on change, so main.cpp isn't recompiled needlessly
    with open(HEADER, "w", encoding="utf-8") as f:
        f.write(text)
print("microHAMCLOCK version " + full)
