static bool mapBit(const MapView &m, int x, int y) {
  return m.bits[y][x >> 3] & (0x80 >> (x & 7));
}

static bool inView(const MapView &m, float lat, float lon) {
  return lon >= m.west && lon < m.east && lat <= m.north && lat > m.south;
}

static void mapXY(const MapView &m, float lat, float lon, int &x, int &y) {
  x = (int)floorf((lon - m.west) / (m.east - m.west) * 128);
  y = (int)floorf((m.north - lat) / (m.north - m.south) * 64);
}

// Is the point inside the Czech borders? (by the Czechia map mask, accurate to ~5 km)
static bool inCzechia(float lat, float lon) {
  if (!inView(MAP_CZECHIA, lat, lon)) return false;
  int x, y;
  mapXY(MAP_CZECHIA, lat, lon, x, y);
  return mapBit(MAP_CZECHIA, x, y);
}

static void renderPskMap() {
  takeSnapshot();
  const MapView *m = &MAP_WORLD;
  if (mapMode == MM_EUROPE) {
    m = &MAP_EUROPE;
  } else if (mapMode == MM_CZECHIA) {
    m = &MAP_CZECHIA;
  } else if (mapMode == MM_AUTO && snapCount) {   // all in Czechia → Czechia, all in Europe → Europe
    bool cr = !homeOk || inCzechia(homeLat, homeLon), eu = !homeOk || inView(MAP_EUROPE, homeLat, homeLon);
    for (int i = 0; i < snapCount && eu; i++) {
      cr = cr && inCzechia(snap[i].lat, snap[i].lon);
      eu = inView(MAP_EUROPE, snap[i].lat, snap[i].lon);
    }
    if (cr) m = &MAP_CZECHIA;
    else if (eu) m = &MAP_EUROPE;
  }
  bool wrap = m->east - m->west >= 360;

  // By day land is filled with dots, at night only the outline remains – forming the grey line.
  // The Czechia map is just the border outline; day and night make no sense on it.
  bool fill = m != &MAP_CZECHIA;
  bool sun = timeValid();
  float decl = 0, subLon = 0;
  if (sun) subsolarPoint(time(nullptr), decl, subLon);
  float sinD = sinf(decl * DEG_TO_RAD), cosD = cosf(decl * DEG_TO_RAD);
  static float cosDl[128];
  for (int x = 0; x < 128; x++) {
    float lon = m->west + (x + 0.5f) * (m->east - m->west) / 128;
    cosDl[x] = cosf((lon - subLon) * DEG_TO_RAD);
  }
  for (int y = 0; y < 64; y++) {
    float lat = (m->north - (y + 0.5f) * (m->north - m->south) / 64) * DEG_TO_RAD;
    float a = sinf(lat) * sinD, b = cosf(lat) * cosD;
    for (int x = 0; x < 128; x++) {
      if (!mapBit(*m, x, y)) continue;
      bool edge = (y > 0 && !mapBit(*m, x, y - 1)) || (y < 63 && !mapBit(*m, x, y + 1));
      if (x > 0 || wrap)   edge |= !mapBit(*m, (x + 127) & 127, y);
      if (x < 127 || wrap) edge |= !mapBit(*m, (x + 1) & 127, y);
      bool day = fill && (!sun || a + b * cosDl[x] > 0);
      if (edge || (day && !((x + y) & 1))) setPixel(x, y);
    }
  }

  uint32_t nowMs = millis();
  bool pulse = (nowMs / 500) & 1;
  int shown = 0;
  for (int i = snapCount - 1; i >= 0; i--) {
    const Spot &s = snap[i];
    if (!inView(*m, s.lat, s.lon)) continue;
    shown++;
    int x, y;
    mapXY(*m, s.lat, s.lon, x, y);
    fillRect(x - 3, y - 3, 7, 7, false);
    if (pulse && nowMs - s.rxMs < NEW_SPOT_BLINK_S * 1000u) {   // a new spot pulses: 5×5 frame ↔ 3×3 square
      fillRect(x - 2, y - 2, 5, 5);
      fillRect(x - 1, y - 1, 3, 3, false);
    } else {
      fillRect(x - 1, y - 1, 3, 3);
    }
  }
  if (homeOk && inView(*m, homeLat, homeLon)) {   // home: hollow square with a dot
    int x, y;
    mapXY(*m, homeLat, homeLon, x, y);
    fillRect(x - 3, y - 3, 7, 7, false);
    fillRect(x - 2, y - 2, 5, 5);
    fillRect(x - 1, y - 1, 3, 3, false);
    setPixel(x, y);
  }

  char buf[8];                                    // number of spots visible on the map
  snprintf(buf, sizeof buf, "%d", shown);
  fillRect(0, 55, textWidth(buf) + 3, 9, false);
  drawText(buf, 1, 57);
}

static void renderStatus() {
  char buf[32];
  drawHeader(tr(S_STATUS), cfg.call);
  char ssid[sizeof cfg.ssid];
  snprintf(buf, sizeof buf, "WIFI %s", wifiUp ? upperCopy(cfg.ssid, ssid, sizeof ssid) : tr(S_NOT_CONNECTED));
  drawText(buf, 0, 12);
  if (wifiUp) {
    snprintf(buf, sizeof buf, "%s %d", WiFi.localIP().toString().c_str(), WiFi.RSSI());
    drawText(buf, 0, 21);
  }
  lock();
  int n = spotCount;
  bool solarOk = solar.ok, ionoOk = iono.ok;
  uint32_t solarAt = solar.fetchedAt, ionoAt = iono.measuredAt;
  char ionoCode[sizeof iono.code];
  strcpy(ionoCode, iono.code);
  unlock();
  snprintf(buf, sizeof buf, "MQTT %s %lu", mqttUp ? "OK" : "--", (unsigned long)spotsTotal);
  drawText(buf, 0, 30);
  snprintf(buf, sizeof buf, tr(S_SPOTS), n);
  drawTextRight(buf, 127, 30);
  // When the solar data arrived and when the ionosonde measured (UTC). The labels are the same
  // in every language: a translated one ("SIRENI") made the line longer than 21 chars.
  auto stamp = [&](const char *name, bool ok, uint32_t at) {
    if (ok && at) {
      time_t t = at;
      struct tm u;
      gmtime_r(&t, &u);
      snprintf(buf, sizeof buf, "%s %02d:%02d", name, u.tm_hour, u.tm_min);
    } else {
      snprintf(buf, sizeof buf, "%s %s", name, ok ? "OK" : "--");
    }
  };
  stamp("SOLAR", solarOk, solarAt);
  drawText(buf, 0, 39);
  stamp("IONO", ionoOk, ionoAt);
  drawTextRight(buf, 127, 39);
  if (ionoOk) drawTextRight(ionoCode, 127, 48);   // which ionosonde (below its measurement time)
  uint32_t min = millis() / 60000;
  snprintf(buf, sizeof buf, tr(S_UPTIME), (unsigned long)(min / 60), (unsigned long)(min % 60));
  drawText(buf, 0, 48);
  drawText(timeValid() ? "NTP OK" : "NTP --", 0, 57);
  snprintf(buf, sizeof buf, "v%s", FW_VERSION_OLED);  // it would not fit next to the callsign in the header
  drawTextRight(buf, 127, 57);
}

static void render() {
  memset(fb, 0, sizeof fb);
  if (wiz != WZ_OFF)        renderWizard();
  else if (portalMode)      renderPortal();
  else if (showStatus)      renderStatus();
  else switch (screen) {
    case S_CLOCK:    renderClock(); break;
    case S_SOLAR:
      renderSolar();
      if ((int32_t)(millis() - solarBlinkUntil) < 0)
        for (uint8_t &b : fb) b = ~b;
      break;
    case S_PSK_LIST: renderPskList(); break;
    case S_PSK_MAP:  renderPskMap(); break;
  }
  if (!portalMode && buttonHeldMs >= CONFIG_HINT_MS) {   // countdown to setup mode
    char buf[24];
    snprintf(buf, sizeof buf, tr(S_SETUP_IN),(unsigned long)((CONFIG_HOLD_MS - buttonHeldMs + 999) / 1000));
    drawLabel(buf);
  } else if ((int32_t)(millis() - flashUntil) < 0) {
    drawLabel(flashText);
  }
}

static void flash(const char *s) {
  strlcpy(flashText, s, sizeof flashText);
  flashUntil = millis() + FLASH_MS;
}


// Power and brightness are sent only on change, I2C commands take time.
static void setDisplay(bool on, uint8_t contrast) {
  static int curOn = -1, curContrast = -1;
  if (on != curOn) {
    oledPower(on);
    curOn = on;
  }
  if (on && contrast != curContrast) {
    oledContrast(contrast);
    curContrast = contrast;
  }
}

// Shifts fb contents by dx, dy pixels right and down ("dim and shift" saver).
static void fbShift(int dx, int dy) {
  if (!dx && !dy) return;
  static uint8_t src[sizeof fb];
  memcpy(src, fb, sizeof fb);
  memset(fb, 0, sizeof fb);
  for (int y = dy; y < 64; y++)
    for (int x = dx; x < 128; x++)
      if (src[((y - dy) >> 3) * 128 + x - dx] & (1 << ((y - dy) & 7))) setPixel(x, y);
}

// ---- button: short press, double click, triple click, long press, 10 s hold ----
// The long press fires once while still held; setup follows after 10 s.

enum ButtonEvent { BTN_NONE, BTN_SHORT, BTN_DOUBLE, BTN_TRIPLE, BTN_LONG, BTN_CONFIG };

static ButtonEvent pollButton(uint32_t now) {
  static bool stable = false, lastRaw = false, configFired = false, longFired = false;
  static uint32_t rawChangedAt, pressedAt, releasedAt;
  static uint8_t clicks;

  bool raw = digitalRead(PIN_BUTTON) == LOW;
  if (raw != lastRaw) {
    lastRaw = raw;
    rawChangedAt = now;
  }
  if (raw != stable && now - rawChangedAt >= 25) {   // debounce
    stable = raw;
    if (stable) {
      pressedAt = now;
      configFired = false;
      longFired = false;
    } else {
      buttonHeldMs = 0;
      if (configFired || longFired) return BTN_NONE;
      clicks++;
      releasedAt = now;
      if (clicks >= 3) {
        clicks = 0;
        return BTN_TRIPLE;
      }
    }
  }
  buttonHeldMs = stable ? now - pressedAt : 0;
  if (stable && !configFired && buttonHeldMs >= CONFIG_HOLD_MS) {
    configFired = true;
    clicks = 0;
    return BTN_CONFIG;
  }
  if (stable && !longFired && !configFired && buttonHeldMs >= LONG_PRESS_MS) {
    longFired = true;
    clicks = 0;
    return BTN_LONG;
  }
  if (!stable && clicks && now - releasedAt >= DOUBLE_CLICK_MS) {
    ButtonEvent e = clicks == 2 ? BTN_DOUBLE : BTN_SHORT;
    clicks = 0;
    return e;
  }
  return BTN_NONE;
}

static void handleButton(uint32_t now) {
  ButtonEvent e = pollButton(now);
  if (portalMode) {                 // in setup mode: short press = back without saving
    if (e == BTN_SHORT && configured() && wiz == WZ_OFF) {
      Serial.println("Hotspot: back without changes, restarting");
      restartSoon(0);
    }
    return;
  }
  // Saver: the first press only wakes the display, no action. The hold for setup always works.
  // Only at the start of a press, not during the whole hold: at night in "dark" the display keeps sleeping and a long press
  // would set wakeSwallow again after the swallow; in the morning it would then swallow another press and the spot wake-up.
  static bool held;
  bool pressStart = buttonHeldMs && !held;
  held = buttonHeldMs != 0;
  if ((pressStart || e != BTN_NONE) && asleep) wakeSwallow = true;
  if (buttonHeldMs || e != BTN_NONE) lastActivity = now;
  if (e == BTN_CONFIG) {
    wakeSwallow = false;
  } else if (e != BTN_NONE && (wakeSwallow || nightDark())) {
    wakeSwallow = false;
    return;
  }
  switch (e) {
    case BTN_CONFIG:
      enterConfigMode();
      break;
    case BTN_SHORT:
      if (showStatus) showStatus = false;
      else screen = (screen + 1) % SCREEN_COUNT;
      screenSince = now;
      break;
    case BTN_DOUBLE:
      cfg.rotate = !cfg.rotate;
      prefs.putBool("rotate", cfg.rotate);
      flash(tr(cfg.rotate ? S_ROTATE_ON : S_ROTATE_OFF));
      screenSince = now;
      break;
    case BTN_TRIPLE:
      showStatus = !showStatus;
      break;
    case BTN_LONG:
      if (showStatus) break;
      if (screen == S_PSK_LIST) {
        sortByDist = !sortByDist;
        prefs.putBool("sortdist", sortByDist);
        flash(tr(sortByDist ? S_SORT_KM : S_SORT_TIME));
      } else if (screen == S_PSK_MAP) {
        mapMode = (mapMode + 1) % MM_COUNT;
        prefs.putUChar("mapmode", mapMode);
        flash(tr(MAP_MODE_NAME[mapMode]));
      }
      screenSince = now;
      break;
    default:
      break;
  }
}

// ============================ SETUP / LOOP ============================

void setup() {
  Serial.begin(115200);
  pinMode(PIN_BUTTON, INPUT_PULLUP);
  digitalWrite(LED_BUILTIN, LOW);
  pinMode(LED_BUILTIN, OUTPUT);
  oledInit();

  prefs.begin(NVS_NAMESPACE, false);
  loadConfig();
  setLanguage(cfgLang(cfg));
  sortByDist = prefs.getBool("sortdist", false);
  mapMode = prefs.getUChar("mapmode", MM_AUTO) % MM_COUNT;
  homeOk = locatorToLatLon(cfg.loc, homeLat, homeLon);

  // Setup mode: the board is not configured, or someone requested it by holding the button.
  // The flag is cleared right away, so a power cycle brings back normal operation.
  portalMode = !configured() || prefs.getBool("portal", false);
  if (prefs.isKey("portal")) prefs.remove("portal");

  dataLock = xSemaphoreCreateMutex();
  delay(500);                       // give the USB bridge time to open the port
  Serial.println();
  Serial.printf("microHAMCLOCK %s for Heltec V3. Commands: setup, status, snapshot\n", FW_VERSION);
  strlcpy(tzRule, tzPosix(cfg.tz), sizeof tzRule);   // loadConfig guaranteed a valid zone
  setenv("TZ", tzRule, 1);
  tzset();
  if (portalMode) portalStart();
  else xTaskCreatePinnedToCore(netTask, "net", 16384, nullptr, 1, nullptr, 0);
  screenSince = lastActivity = millis();
}

// Saver: after inactivity (or at night with "dark") the display turns off, runs
// Game of Life, or dims and shifts. A new spot is activity if the
// settings and night allow it; it wakes the display straight on the spot list.
static void saverService(uint32_t now) {
  static uint32_t seenSpotWake;
  static bool ledLit;
  static uint32_t ledStartedAt;
  if (ledLit && now - ledStartedAt >= SPOT_LED_MS) {
    digitalWrite(LED_BUILTIN, LOW);
    ledLit = false;
  }
  bool busy = portalMode || wiz != WZ_OFF || buttonHeldMs >= CONFIG_HINT_MS;
  if (saverForced && (busy || (int32_t)(lastActivity - saverForcedAt) > 0)) {   // woken: back to normal
    saverForced = false;
    saverForceMode = -1;
  }
  bool wokeBySpot = false;
  uint32_t sw = spotWakeAt;
  if (sw != seenSpotWake) {
    seenSpotWake = sw;
    if (cfg.wakeOnSpot && (cfg.nightMode == NM_SPOTS || !isNight())) {
      if (asleep && !busy && !buttonHeldMs && !wakeSwallow && !nightDark()) {
        screen = S_PSK_LIST;
        showStatus = false;
        screenSince = now;
        wokeBySpot = true;
      }
      lastActivity = now;
    }
  }
  bool idle = cfg.saverMin && now - lastActivity >= cfg.saverMin * 60000UL;
  bool was = asleep;
  asleep = !busy && (idle || nightDark() || saverForced);
  if (asleep && !was) {
    lifeReset(esp_random());
    Serial.println("Screen saver: on");
  } else if (was && !asleep) {
    Serial.println("Screen saver: off");
    if (wokeBySpot && cfg.ledOnSpotWake) {
      digitalWrite(LED_BUILTIN, HIGH);
      ledStartedAt = now;
      ledLit = true;
    }
  }
}

static SaverMode saverModeNow() {
  if (saverForceMode >= 0) return SaverMode(saverForceMode);
  return nightDark() ? SV_OFF : SaverMode(cfg.saverMode);
}

static void showFrame(uint32_t now) {
  SaverMode mode = saverModeNow();
  if (asleep && mode == SV_OFF) {
    setDisplay(false, 0);
    return;
  }
  if (asleep && mode == SV_LIFE) {
    lifeStep();
    lifeRender(fb);
    setDisplay(true, cfg.bright[BR_LIFE]);
  } else {
    render();
    if (asleep) {                   // dim and shift: shift by 0–2 px, changes every minute
      static const int8_t SHIFT[4][2] = {{0, 0}, {2, 0}, {2, 2}, {0, 2}};
      const int8_t *d = SHIFT[(now / (DIM_SHIFT_S * 1000UL)) % 4];
      fbShift(d[0], d[1]);
    }
    uint8_t c = cfg.bright[asleep ? BR_DIM : isNight() ? BR_NIGHT : BR_DAY];
    if (previewUntil && (int32_t)(now - previewUntil) < 0) c = previewContrast;
    setDisplay(true, c);
  }
  oledFlush();
}

void loop() {
  static uint32_t nextFrame;
  uint32_t now = millis();

  serialService();
  usbService();
  handleButton(now);
  if (portalMode) portalService();
  if (restartPending && (int32_t)(now - restartAt) >= 0) ESP.restart();
  saverService(now);

  if (blinkTestAt && !portalMode && wiz == WZ_OFF) {   // test: show the propagation screen and a moment later "new data"
    screen = S_SOLAR;
    showStatus = false;
    screenSince = lastActivity = now;
    if ((int32_t)(now - blinkTestAt) >= 0) {
      blinkTestAt = 0;
      propagationSeq++;
    }
  }

  // New propagation data: the propagation screen briefly inverts, but only when it is showing.
  static uint32_t seenPropagation;
  uint32_t seq = propagationSeq;
  if (seq != seenPropagation) {
    seenPropagation = seq;
    if (screen == S_SOLAR && !showStatus && !asleep && !portalMode && wiz == WZ_OFF) {
      solarBlinkUntil = now + DATA_BLINK_MS;
      nextFrame = now;              // redraw now, not after FRAME_MS
    }
  }

  if (cfg.rotate && !portalMode && !showStatus && wiz == WZ_OFF && now - screenSince >= cfg.rotateSec * 1000UL) {
    screen = (screen + 1) % SCREEN_COUNT;
    screenSince = now;
  }
  if ((int32_t)(now - nextFrame) >= 0) {
    nextFrame = now + (asleep && saverModeNow() == SV_LIFE ? LIFE_STEP_MS : FRAME_MS);
    showFrame(now);
  }
  delay(1);
}
