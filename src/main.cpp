static void loadConfig() {
  memset(&cfg, 0, sizeof cfg);
  loadString("ssid", cfg.ssid, sizeof cfg.ssid);
  loadString("pass", cfg.pass, sizeof cfg.pass);
  loadString("call", cfg.call, sizeof cfg.call);
  loadString("loc", cfg.loc, sizeof cfg.loc);
  loadString("lang", cfg.lang, sizeof cfg.lang);
  Lang l;
  if (!langFromCode(cfg.lang, l)) l = LANG_EN;          // unknown or missing language → English
  strlcpy(cfg.lang, langInfo(l).code, sizeof cfg.lang);

  loadString("tzid", cfg.tz, sizeof cfg.tz);
  char id[sizeof cfg.tz];
  if (!tzPosix(cfg.tz, id, sizeof id)) {
    // No zone: a previously configured board ran on CET/CEST, a new one starts in UTC.
    tzPosix(configured() ? LEGACY_TZ : DEFAULT_TZ, id, sizeof id);
  }
  strlcpy(cfg.tz, id, sizeof cfg.tz);

  cfg.saverMin = min<int>(prefs.getUChar("svmin", DEFAULT_SAVER_MIN), MAX_SAVER_MIN);
  cfg.saverMode = prefs.getUChar("svmode", SV_OFF) % SV_MODE_COUNT;
  cfg.wakeOnSpot = prefs.getBool("svspot", true);
  cfg.ledOnSpotWake = prefs.getBool("svled", true);
  cfg.rotate = prefs.getBool("rotate", DEFAULT_ROTATE);
  cfg.rotateSec = constrain(prefs.getUChar("rotsec", DEFAULT_ROTATE_S), MIN_ROTATE_S, MAX_ROTATE_S);
  cfg.nightFrom = prefs.getUChar("nfrom", DEFAULT_NIGHT_FROM) % 24;
  cfg.nightTo = prefs.getUChar("nto", DEFAULT_NIGHT_TO) % 24;
  cfg.nightMode = prefs.getUChar("nmode", NM_SPOTS) % NM_MODE_COUNT;
  for (int i = 0; i < BR_COUNT; i++) cfg.bright[i] = prefs.getUChar(BRIGHT_KEY[i], BRIGHT_DEFAULT[i]);
  cfg.nvisMargin = min<int>(prefs.getUChar("nvismg", 0), MAX_NVIS_MARGIN);
  cfg.nvis60 = prefs.getBool("nvis60", true);
  loadString("iono", cfg.iono, sizeof cfg.iono);
}

