// Reads chars from the serial line; returns true when a whole line is complete.
// A line starting with STX (0x02) comes from the web installer: it is not echoed (it may hold a password).
static bool readLine(bool secret) {
  static bool lastCR, page;
  while (Serial.available()) {
    char c = Serial.read();
    if (c == '\n' && lastCR) { lastCR = false; continue; }   // CRLF = one Enter
    lastCR = c == '\r';
    if (c == 2 && !lineLen) {
      page = true;
      continue;
    }
    if (c == '\r' || c == '\n') {
      line[lineLen] = 0;
      lineLen = 0;
      if (!page) Serial.println();
      lineFromPage = page;
      page = false;
      return true;
    }
    if (c == 8 || c == 127) {                                // backspace
      if (lineLen) {
        lineLen--;
        if (!page) Serial.print("\b \b");
      }
    } else if (c >= 32 && lineLen < sizeof line - 1) {
      line[lineLen++] = c;
      if (!page) Serial.print(secret ? '*' : c);
    }
  }
  return false;
}

static void trim(char *s) {
  int n = strlen(s);
  while (n && isspace((unsigned char)s[n - 1])) s[--n] = 0;
  int i = 0;
  while (isspace((unsigned char)s[i])) i++;
  if (i) memmove(s, s + i, n - i + 1);
}

