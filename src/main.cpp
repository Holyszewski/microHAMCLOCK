// Network list: each only once (the strongest), sorted by signal strength.
static void collectScan(int n) {
  int idx[MAX_NETS], count = 0;
  for (int i = 0; i < n; i++) {
    String s = WiFi.SSID(i);
    if (!s.length()) continue;
    bool dup = false;
    for (int j = 0; j < count && !dup; j++) dup = WiFi.SSID(idx[j]) == s;
    if (dup) continue;
    if (count < MAX_NETS) idx[count++] = i;
  }
  for (int i = 1; i < count; i++)
    for (int j = i; j > 0 && WiFi.RSSI(idx[j]) > WiFi.RSSI(idx[j - 1]); j--) std::swap(idx[j], idx[j - 1]);
  for (int i = 0; i < count; i++) {
    nets[i].ssid = WiFi.SSID(idx[i]);
    nets[i].rssi = WiFi.RSSI(idx[i]);
    nets[i].open = WiFi.encryptionType(idx[i]) == WIFI_AUTH_OPEN;
  }
  netCount = count;
  WiFi.scanDelete();
}

