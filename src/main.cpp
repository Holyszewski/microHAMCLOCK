static uint32_t spotAge(const Spot &s, uint32_t nowUnix, uint32_t nowMs) {
  if (nowUnix && s.t && nowUnix >= s.t) return nowUnix - s.t;
  return (nowMs - s.rxMs) / 1000;
}

// The same station on the same band is just updated.
static void addSpot(const Spot &s) {
  lock();
  int slot = -1, oldest = 0;
  for (int i = 0; i < spotCount; i++) {
    if (!strcmp(spots[i].call, s.call) && !strcmp(spots[i].band, s.band)) { slot = i; break; }
    if (spots[i].t < spots[oldest].t) oldest = i;
  }
  if (slot < 0) slot = spotCount < MAX_SPOTS ? spotCount++ : oldest;
  spots[slot] = s;
  unlock();
}

static void expireSpots() {
  uint32_t nowUnix = timeValid() ? time(nullptr) : 0, nowMs = millis();
  lock();
  int j = 0;
  for (int i = 0; i < spotCount; i++)
    if (spotAge(spots[i], nowUnix, nowMs) < SPOT_WINDOW_MIN * 60u) spots[j++] = spots[i];
  spotCount = j;
  unlock();
}

// ============================ PSKREPORTER (MQTT) ============================
// Minimal MQTT 3.1.1 client: CONNECT, SUBSCRIBE (QoS 0), PINGREQ and receiving PUBLISH.
// Topics look like pskr/filter/v2/band/mode/sender/receiver/sloc/rloc/sdxcc/rdxcc,
// a slash in a callsign is replaced by a dot in the topic.

enum MqttState { MS_IDLE, MS_WAIT_CONNACK, MS_WAIT_SUBACK, MS_READY };
static WiFiClient mqttNet;
static MqttState mqttState = MS_IDLE;
static uint32_t mqttStateSince, mqttLastRx, mqttLastTx, mqttNextTry, mqttBackoff = 5000;
static uint8_t mqttBuf[1024];

static size_t putLen(uint8_t *p, uint32_t n) {
  size_t i = 0;
  do {
    uint8_t b = n & 0x7F;
    n >>= 7;
    p[i++] = b | (n ? 0x80 : 0);
  } while (n);
  return i;
}

static size_t putStr(uint8_t *p, const char *s) {
  size_t n = strlen(s);
  p[0] = n >> 8;
  p[1] = n & 0xFF;
  memcpy(p + 2, s, n);
  return n + 2;
}

static void mqttSend(uint8_t type, const uint8_t *body, size_t len) {
  uint8_t hdr[5];
  hdr[0] = type;
  size_t h = 1 + putLen(hdr + 1, len);
  mqttNet.write(hdr, h);
  if (len) mqttNet.write(body, len);
  mqttLastTx = millis();
}

static void mqttSetState(MqttState s) {
  mqttState = s;
  mqttStateSince = millis();
  mqttUp = s == MS_READY;
}

static void mqttDrop(const char *why) {
  if (mqttState != MS_IDLE && !quietLog) Serial.printf("MQTT: disconnected (%s)\n", why);
  mqttNet.stop();
  mqttSetState(MS_IDLE);
  mqttNextTry = millis() + mqttBackoff;
  mqttBackoff = min<uint32_t>(mqttBackoff * 2, 120000);
}

static void mqttConnect() {
  if (!mqttNet.connect(MQTT_HOST, MQTT_PORT, 5000)) {
    mqttDrop("cannot connect");
    if (!quietLog) Serial.println("MQTT: server not responding");
    return;
  }
  mqttNet.setNoDelay(true);
  char id[24];
  snprintf(id, sizeof id, "microhamclock-%08lx", (unsigned long)esp_random());
  uint8_t body[64];
  size_t n = putStr(body, "MQTT");
  body[n++] = 4;                    // version 3.1.1
  body[n++] = 0x02;                 // clean session
  body[n++] = 0;
  body[n++] = 60;                   // keepalive 60 s
  n += putStr(body + n, id);
  mqttSend(0x10, body, n);
  mqttLastRx = millis();
  mqttSetState(MS_WAIT_CONNACK);
}

// Base form of a callsign: the longest part between slashes (OK2MTB/P → OK2MTB, DL/OK2MTB → OK2MTB).
static void baseCall(const char *call, char *out, size_t n) {
  const char *best = call;
  size_t bestLen = 0;
  for (const char *p = call; *p;) {
    size_t len = strcspn(p, "/");
    if (len > bestLen) { best = p; bestLen = len; }
    p += len;
    if (*p) p++;
  }
  bestLen = min(bestLen, n - 1);
  memcpy(out, best, bestLen);
  out[bestLen] = 0;
}

// Subscribes to the callsign as entered, its base form and the base with CALL_SUFFIXES.
static void mqttSubscribe() {
  const int MAX_CALLS = 2 + sizeof CALL_SUFFIXES / sizeof CALL_SUFFIXES[0];
  char calls[MAX_CALLS][16], base[12];
  int count = 0;
  baseCall(cfg.call, base, sizeof base);
  auto add = [&](const char *c) {
    for (int i = 0; i < count; i++) if (!strcmp(calls[i], c)) return;
    strlcpy(calls[count++], c, sizeof calls[0]);
  };
  add(cfg.call);
  add(base);
  for (const char *suffix : CALL_SUFFIXES) {
    char c[16];
    snprintf(c, sizeof c, "%s/%s", base, suffix);
    add(c);
  }

  uint8_t body[256];
  body[0] = 0;
  body[1] = 1;                      // message identifier
  size_t n = 2;
  for (int i = 0; i < count; i++) {
    char topic[64] = "pskr/filter/v2/+/+/";
    size_t t = strlen(topic);
    for (const char *c = calls[i]; *c && t < sizeof topic - 3; c++) topic[t++] = *c == '/' ? '.' : *c;
    strcpy(topic + t, "/#");
    n += putStr(body + n, topic);
    body[n++] = 0;                  // QoS 0
    if (!quietLog) Serial.printf("MQTT: subscribing to %s\n", topic);
  }
  mqttSend(0x82, body, n);
  mqttSetState(MS_WAIT_SUBACK);
}

// ---- simple parsing of PSKReporter's flat JSON ----

static const char *jsonFind(const char *js, const char *key) {
  char pat[16];
  snprintf(pat, sizeof pat, "\"%s\":", key);
  const char *p = strstr(js, pat);
  return p ? p + strlen(pat) : nullptr;
}

static bool jsonStr(const char *js, const char *key, char *out, size_t n) {
  const char *p = jsonFind(js, key);
  if (!p || *p != '"') return false;
  size_t i = 0;
  for (p++; *p && *p != '"' && i + 1 < n; p++) out[i++] = *p;
  out[i] = 0;
  return i > 0;
}

static bool jsonLong(const char *js, const char *key, long &v) {
  const char *p = jsonFind(js, key);
  if (!p) return false;
  char *end;
  v = strtol(p, &end, 10);
  return end != p;
}

// {"sq":…,"f":14074000,"md":"FT8","rp":-12,"t":1791562589,"sc":"OK1ABC","sl":"JO70va",
//  "rc":"DL1XYZ","rl":"JO62qm","sa":503,"ra":230,"b":"20m"}
static void handleSpot(const char *js) {
  Spot s = {};
  char loc[12];
  long snr = 0, t = 0;
  if (!jsonStr(js, "rc", s.call, sizeof s.call) || !jsonStr(js, "rl", loc, sizeof loc)) return;
  for (char *c = s.call; *c; c++) *c = toupper((unsigned char)*c);   // the font would draw a lowercase "s" as lowercase
  if (!strcmp(s.call, "N0CALL")) return;   // default callsign in programs where nobody has set one
  if (!locatorToLatLon(loc, s.lat, s.lon)) return;
  jsonStr(js, "b", s.band, sizeof s.band);
  jsonLong(js, "rp", snr);
  jsonLong(js, "t", t);
  s.snr = constrain(snr, -99, 99);
  s.t = t;
  s.rxMs = millis();
  s.km = homeOk ? (uint16_t)lroundf(distanceKm(homeLat, homeLon, s.lat, s.lon)) : 0;
  addSpot(s);
  spotsTotal++;
  // Only fresh spots wake: some programs send reports delayed by even hours.
  uint32_t nowUnix = timeValid() ? time(nullptr) : 0;
  if (!nowUnix || !s.t || nowUnix < s.t + SPOT_WAKE_MAX_AGE_MIN * 60u) spotWakeAt = millis() | 1;
  if (!quietLog) Serial.printf("Spot: %s %s %+d dB %u km\n", s.call, s.band, s.snr, s.km);
}

static void mqttPacket(uint8_t type, const uint8_t *p, uint32_t len) {
  switch (type >> 4) {
    case 2:                         // CONNACK
      if (len >= 2 && p[1] == 0) {
        if (!quietLog) Serial.println("MQTT: connected");
        mqttBackoff = 5000;
        mqttSubscribe();
      } else {
        mqttDrop("server refused the connection");
      }
      break;
    case 9: {                       // SUBACK: after the identifier, one result per topic
      bool ok = len >= 3;
      for (uint32_t i = 2; i < len; i++) ok &= p[i] != 0x80;
      if (ok) mqttSetState(MS_READY);
      else mqttDrop("subscription refused");
      break;
    }
    case 3: {                       // PUBLISH
      if (len < 2) break;
      uint32_t off = 2 + (p[0] << 8 | p[1]);
      if (type & 0x06) off += 2;    // QoS > 0 has a message identifier
      if (off >= len) break;
      char js[sizeof mqttBuf + 1];
      memcpy(js, p + off, len - off);
      js[len - off] = 0;
      handleSpot(js);
      break;
    }
    default:                        // PINGRESP and the rest are enough as a sign of life
      break;
  }
}

static void mqttPoll() {
  static uint8_t type;
  static uint32_t len, got, mult;
  static int part;                  // 0 = header, 1 = length, 2 = payload
  while (mqttNet.available()) {
    uint8_t b = mqttNet.read();
    mqttLastRx = millis();
    if (part == 0) {
      type = b;
      len = got = 0;
      mult = 1;
      part = 1;
    } else if (part == 1) {
      len += (b & 0x7F) * mult;
      mult <<= 7;
      if (!(b & 0x80)) part = len ? 2 : 0;
      if (!part) mqttPacket(type, mqttBuf, 0);
    } else {
      if (got < sizeof mqttBuf) mqttBuf[got] = b;   // overly long messages are dropped
      if (++got == len) {
        if (len <= sizeof mqttBuf) mqttPacket(type, mqttBuf, len);
        part = 0;
      }
    }
  }
}

static void mqttService() {
  uint32_t now = millis();
  if (mqttState == MS_IDLE) {
    if (cfg.call[0] && (int32_t)(now - mqttNextTry) >= 0) mqttConnect();
    return;
  }
  if (!mqttNet.connected()) { mqttDrop("connection lost"); return; }
  mqttPoll();
  now = millis();                   // mqttPoll may have moved times forward, an older "now" would underflow
  if (mqttState == MS_IDLE) return;
  if (mqttState != MS_READY && now - mqttStateSince > 10000) { mqttDrop("server did not respond"); return; }
  if (now - mqttLastTx > 30000) mqttSend(0xC0, nullptr, 0);   // PINGREQ
  if (now - mqttLastRx > 100000) mqttDrop("no reply to ping");
}

