static void portalStart() {
  WiFi.onEvent([](WiFiEvent_t, WiFiEventInfo_t) { Serial.println("Hotspot: a device connected"); },
               ARDUINO_EVENT_WIFI_AP_STACONNECTED);
  WiFi.onEvent([](WiFiEvent_t, WiFiEventInfo_t info) {
    Serial.printf("Hotspot: DHCP assigned %s\r\n", IPAddress(info.wifi_ap_staipassigned.ip.addr).toString().c_str());
  }, ARDUINO_EVENT_WIFI_AP_STAIPASSIGNED);
  WiFi.mode(WIFI_AP_STA);           // STA part only for scanning networks
  uint8_t mac[6];
  WiFi.macAddress(mac);             // only after Wi-Fi is on, otherwise it returns zeros
  snprintf(apName, sizeof apName, "MICROHAMCLOCK-%02X%02X", mac[4], mac[5]);
  WiFi.softAPConfig(PORTAL_IP, PORTAL_IP, IPAddress(255, 255, 255, 0));
  WiFi.softAP(apName);              // open network, runs only during setup

  // Arduino core 2.x does not let DHCP send the DNS server address. The phone then never
  // asks our DNS, does not detect the sign-in page and does not open it by itself.
  esp_netif_t *ap = esp_netif_get_handle_from_ifkey("WIFI_AP_DEF");
  if (ap) {
    esp_netif_dhcps_stop(ap);
    esp_netif_dns_info_t dnsInfo = {};
    dnsInfo.ip.type = ESP_IPADDR_TYPE_V4;
    dnsInfo.ip.u_addr.ip4.addr = static_cast<uint32_t>(WiFi.softAPIP());
    esp_netif_set_dns_info(ap, ESP_NETIF_DNS_MAIN, &dnsInfo);
    dhcps_offer_t offer = OFFER_DNS;
    esp_netif_dhcps_option(ap, ESP_NETIF_OP_SET, ESP_NETIF_DOMAIN_NAME_SERVER, &offer, sizeof offer);
    esp_netif_dhcps_start(ap);
  }
  dnsUdp.begin(53);
  web.on("/", HTTP_GET, handleRoot);
  web.on("/save", HTTP_POST, handleSave);
  web.on("/cancel", HTTP_POST, handleCancel);
  web.on("/factory", HTTP_POST, handleFactory);
  web.on("/bright", HTTP_GET, handleBright);
  web.on("/nets", HTTP_GET, handleNets);
  web.addHandler(new CatchAll());   // after the other paths, redirects everything left
  web.begin();
  startScan();
  portalSeenAt = millis();
  Serial.printf("Setup mode: join Wi-Fi %s (no password) and open http://%s\r\n", apName,
                PORTAL_IP.toString().c_str());
  Serial.println("Or type setup here in the console.");
}

// Picks up the result of startScan(). The core reports a failure after 6 s (300 ms per channel
// × 20), but with the hotspot on the radio keeps returning to its channel and the scan takes
// about 8 s and then finishes fine, so we wait for the result ourselves. An empty or failed
// scan (often the first one after the hotspot starts) is repeated.
static void scanService() {
  if (!scanRunning) return;
  int n = WiFi.scanComplete();
  if (n < 0 && !scanStartFailed) {
    if (millis() - scanStartedAt < SCAN_TIMEOUT_MS) return;
    esp_wifi_scan_stop();
  }
  if (n <= 0 && scanTriesLeft) {
    scanTriesLeft--;
    Serial.println("WiFi scan: nothing found, trying again");
    scanBegin();
    return;
  }
  collectScan(n > 0 ? n : 0);
  scanRunning = false;
}

static void portalService() {
  dnsService();
  web.handleClient();
  scanService();
  uint32_t now = millis();
  if (WiFi.softAPgetStationNum() > 0) portalSeenAt = now;
  // A configured board returns by itself after a while (e.g. when the hotspot was started by mistake).
  if (configured() && wiz == WZ_OFF && now - portalSeenAt > PORTAL_IDLE_MIN * 60000UL) {
    Serial.println("Hotspot: nobody connected, returning to normal operation");
    restartSoon(0);
  }
}

