// ============================ USB SETUP (WEB INSTALLER) ============================
// The web installer page sets the basics over Web Serial. Its commands are lines starting with
// STX (0x02), which are not echoed; every reply is one line starting with "HC ":
//   info             → HC info {version, settings without the password, languages, time zones}
//   scan             → HC scan [{ssid, rssi, open}, …] once the Wi-Fi scan is done
//   save k=v&k=v…    → HC ok and a restart, or HC error {field, msg}
// "save" takes lang, ssid, pass, open, call, loc and tz, URL-encoded (encodeURIComponent).
// Without pass the stored password stays; open=1 means a network without a password.

static bool usbScanWanted;

static void jsonPrint(const char *s) {  // prints a JSON string with escapes
  Serial.print('"');
  for (; *s; s++) {
    if (*s == '"' || *s == '\\') Serial.print('\\');
    if ((uint8_t)*s < 32) Serial.printf("\\u%04x", *s);
    else                  Serial.print(*s);
  }
  Serial.print('"');
}

// Value of key in "k=v&k=v", URL-decoded; found says whether the key was there at all.
static String urlValue(const char *q, const char *key, bool *found = nullptr) {
  size_t kn = strlen(key);
  if (found) *found = false;
  for (const char *p = q; *p;) {
    const char *end = strchr(p, '&');
    if (!end) end = p + strlen(p);
    if (!strncmp(p, key, kn) && p[kn] == '=') {
      if (found) *found = true;
      String v;
      for (const char *c = p + kn + 1; c < end; c++) {
        if (*c == '%' && c + 2 < end && isxdigit((unsigned char)c[1]) && isxdigit((unsigned char)c[2])) {
          char hex[3] = {c[1], c[2], 0};
          v += (char)strtol(hex, nullptr, 16);
          c += 2;
        } else {
          v += *c;
        }
      }
      return v;
    }
    p = *end ? end + 1 : end;
  }
  return String();
}

