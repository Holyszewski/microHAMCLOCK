static String htmlEscape(const char *s) {
  String o;
  for (; *s; s++) {
    switch (*s) {
      case '&':  o += "&amp;"; break;
      case '<':  o += "&lt;"; break;
      case '>':  o += "&gt;"; break;
      case '"':  o += "&quot;"; break;
      case '\'': o += "&#39;"; break;
      default:   o += *s;
    }
  }
  return o;
}

