// ---- custom DNS: answers every name with the hotspot address ----
// Type A (IPv4) queries get the hotspot address, others (mainly AAAA) an empty
// answer without error. Unlike the DNSServer library it also handles queries with EDNS.

static WiFiUDP dnsUdp;

static void dnsService() {
  int len = dnsUdp.parsePacket();
  if (len <= 0) return;
  uint8_t q[512], r[512 + 16];
  if (len > (int)sizeof q || len < 12) {
    dnsUdp.flush();
    return;
  }
  dnsUdp.read(q, len);
  if ((q[2] & 0x80) || (q[4] << 8 | q[5]) != 1) return;   // only queries with a single question

  char name[64];
  int p = 12, n = 0;
  while (p < len && q[p]) {
    int l = q[p++];
    if ((l & 0xC0) || p + l > len) return;
    for (int i = 0; i < l; i++, p++) if (n < (int)sizeof name - 2) name[n++] = q[p];
    name[n++] = '.';
  }
  if (n) n--;
  name[n] = 0;
  p++;                                                     // null terminator of the name
  if (p + 4 > len) return;
  uint16_t qtype = q[p] << 8 | q[p + 1];
  p += 4;                                                  // type and class

  memcpy(r, q, p);                                         // header and question copied back
  r[2] = 0x84 | (q[2] & 0x01);                             // response, authoritative, RD as in the query
  r[3] = 0x80;                                             // RA, no error
  r[6] = r[7] = r[8] = r[9] = r[10] = r[11] = 0;
  int out = p;
  if (qtype == 1 || qtype == 255) {                        // A or ANY
    static const uint8_t ans[] = {0xC0, 0x0C, 0, 1, 0, 1, 0, 0, 0, 10, 0, 4};   // TTL 10 s
    memcpy(r + out, ans, sizeof ans);
    out += sizeof ans;
    IPAddress ip = WiFi.softAPIP();
    for (int i = 0; i < 4; i++) r[out++] = ip[i];
    r[7] = 1;
  }
  dnsUdp.beginPacket(dnsUdp.remoteIP(), dnsUdp.remotePort());
  dnsUdp.write(r, out);
  dnsUdp.endPacket();
}

// Catches all other paths. With onNotFound the core would log an error to the console for each one.
class CatchAll : public RequestHandler {
  bool canHandle(HTTPMethod, String) override { return true; }
  bool handle(WebServer &, HTTPMethod, String) override {
    handleOther();
    return true;
  }
};

static void portalStart() {
  WiFi.onEvent([](WiFiEvent_t, WiFiEventInfo_t) { Serial.println("Hotspot: a device connected"); },
               ARDUINO_EVENT_WIFI_AP_STACONNECTED);
  WiFi.onEvent([](WiFiEvent_t, WiFiEventInfo_t info) {
    Serial.printf("Hotspot: DHCP assigned %s\n", IPAddress(info.wifi_ap_staipassigned.ip.addr).toString().c_str());
  }, ARDUINO_EVENT_WIFI_AP_STAIPASSIGNED);
  WiFi.mode(WIFI_AP_STA);           // STA part only for scanning networks
  uint8_t mac[6];
  WiFi.macAddress(mac);             // only after Wi-Fi is on, otherwise it returns zeros
  snprintf(apName, sizeof apName, "MICROHAMCLOCK-%02X%02X", mac[4], mac[5]);
  WiFi.softAPConfig(PORTAL_IP, PORTAL_IP, IPAddress(255, 255, 255, 0));
  WiFi.softAP(apName);              // open network, runs only during setup

  // Arduino core 2.x does not let DHCP send the DNS server address. The phone then never
  // asks our DNS, does not detect the sign-in page and does not open it by itself.
  esp_netif_t *ap = esp_netif_get_handle_from_ifkey("WIFI_AP_DEF");
  if (ap) {
    esp_netif_dhcps_stop(ap);
    esp_netif_dns_info_t dnsInfo = {};
    dnsInfo.ip.type = ESP_IPADDR_TYPE_V4;
    dnsInfo.ip.u_addr.ip4.addr = static_cast<uint32_t>(WiFi.softAPIP());
    esp_netif_set_dns_info(ap, ESP_NETIF_DNS_MAIN, &dnsInfo);
    dhcps_offer_t offer = OFFER_DNS;
    esp_netif_dhcps_option(ap, ESP_NETIF_OP_SET, ESP_NETIF_DOMAIN_NAME_SERVER, &offer, sizeof offer);
    esp_netif_dhcps_start(ap);
  }
  dnsUdp.begin(53);
  web.on("/", HTTP_GET, handleRoot);
  web.on("/save", HTTP_POST, handleSave);
  web.on("/cancel", HTTP_POST, handleCancel);
  web.on("/bright", HTTP_GET, handleBright);
  web.addHandler(new CatchAll());   // after the other paths, redirects everything left
  web.begin();
  startScan();
  portalSeenAt = millis();
  Serial.printf("Setup mode: join Wi-Fi %s (no password) and open http://%s\n", apName,
                PORTAL_IP.toString().c_str());
  Serial.println("Or type setup here in the console.");
}

