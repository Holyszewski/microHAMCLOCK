// Callsign: uppercase letters, digits and slash, 3–11 chars.
static bool normalizeCall(char *s) {
  int n = strlen(s);
  if (n < 3 || n > 11) return false;
  for (int i = 0; i < n; i++) {
    s[i] = toupper((unsigned char)s[i]);
    if (!isalnum((unsigned char)s[i]) && s[i] != '/') return false;
  }
  return true;
}

// Locator: AA00 or AA00aa, returned in the usual form (JO70va).
static bool normalizeLocator(char *s) {
  int n = strlen(s);
  if (n != 4 && n != 6) return false;
  for (int i = 0; i < n; i++) s[i] = i < 2 ? toupper((unsigned char)s[i]) : tolower((unsigned char)s[i]);
  if (s[0] < 'A' || s[0] > 'R' || s[1] < 'A' || s[1] > 'R') return false;
  if (!isdigit((unsigned char)s[2]) || !isdigit((unsigned char)s[3])) return false;
  if (n == 6 && (s[4] < 'a' || s[4] > 'x' || s[5] < 'a' || s[5] > 'x')) return false;
  return true;
}

// ============================ GEOGRAPHY ============================

// Center of a locator square (4, 6 or more chars; longer ones are cut to 6).
static bool locatorToLatLon(const char *loc, float &lat, float &lon) {
  int n = strlen(loc);
  if (n < 4) return false;
  char a = toupper(loc[0]), b = toupper(loc[1]);
  if (a < 'A' || a > 'R' || b < 'A' || b > 'R' || !isdigit((unsigned char)loc[2]) || !isdigit((unsigned char)loc[3])) return false;
  lon = (a - 'A') * 20.0f - 180.0f + (loc[2] - '0') * 2.0f;
  lat = (b - 'A') * 10.0f - 90.0f + (loc[3] - '0') * 1.0f;
  char c = n >= 6 ? tolower(loc[4]) : 0, d = n >= 6 ? tolower(loc[5]) : 0;
  if (c >= 'a' && c <= 'x' && d >= 'a' && d <= 'x') {
    lon += (c - 'a') * (2.0f / 24) + 1.0f / 24;
    lat += (d - 'a') * (1.0f / 24) + 0.5f / 24;
  } else {
    lon += 1.0f;
    lat += 0.5f;
  }
  return true;
}

static float distanceKm(float lat1, float lon1, float lat2, float lon2) {
  const float R = 6371.0f, D = PI / 180;
  float dlat = (lat2 - lat1) * D, dlon = (lon2 - lon1) * D;
  float a = sinf(dlat / 2) * sinf(dlat / 2) + cosf(lat1 * D) * cosf(lat2 * D) * sinf(dlon / 2) * sinf(dlon / 2);
  return 2 * R * atan2f(sqrtf(a), sqrtf(1 - a));
}

// Point where the Sun is at the zenith (approximation, accurate to ~1°).
static void subsolarPoint(time_t t, float &decl, float &lon) {
  double n = (t - 946728000.0) / 86400.0;            // days since J2000.0
  double L = fmod(280.460 + 0.9856474 * n, 360.0);
  double g = fmod(357.528 + 0.9856003 * n, 360.0) * DEG_TO_RAD;
  double lambda = (L + 1.915 * sin(g) + 0.020 * sin(2 * g)) * DEG_TO_RAD;
  double eps = (23.439 - 0.0000004 * n) * DEG_TO_RAD;
  double ra = atan2(cos(eps) * sin(lambda), cos(lambda)) * RAD_TO_DEG;
  double gmst = fmod(280.46061837 + 360.98564736629 * n, 360.0);
  decl = asin(sin(eps) * sin(lambda)) * RAD_TO_DEG;
  lon = fmod(ra - gmst + 540.0, 360.0) - 180.0;
}

// Days since 1 Jan 1970 (newlib has no timegm, so UTC time is assembled by hand).
static int32_t daysFromCivil(int y, int m, int d) {
  y -= m <= 2;
  int era = (y >= 0 ? y : y - 399) / 400;
  int yoe = y - era * 400;
  int doy = (153 * (m + (m > 2 ? -3 : 9)) + 2) / 5 + d - 1;
  int doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
  return era * 146097 + doe - 719468;
}

static bool timeValid() { return time(nullptr) > 1700000000; }

// Night per settings (local time). Without valid time there is no night.
static bool isNight() {
  if (!timeValid() || cfg.nightFrom == cfg.nightTo) return false;
  time_t t = time(nullptr);
  struct tm l;
  localtime_r(&t, &l);
  int h = l.tm_hour;
  return cfg.nightFrom > cfg.nightTo ? (h >= cfg.nightFrom || h < cfg.nightTo)
                                     : (h >= cfg.nightFrom && h < cfg.nightTo);
}

