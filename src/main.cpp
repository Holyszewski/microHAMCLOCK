// Downloads a public page over HTTPS (the certificate is not verified, the data is not secret).
static bool httpsGet(const char *url, const char *what, String &out) {
  WiFiClientSecure tls;
  tls.setInsecure();
  HTTPClient http;
  http.setTimeout(10000);
  http.setUserAgent(String("microHAMCLOCK/") + FW_VERSION + " (https://github.com/Holyszewski/microHAMCLOCK)");
  if (!http.begin(tls, url)) return false;
  int code = http.GET();
  if (code == 200) out = http.getString();
  http.end();
  if (code != 200 && !quietLog) Serial.printf("%s: HTTP %d\r\n", what, code);
  return code == 200 && out.length();
}

static void xmlValue(const String &x, const char *tag, char *out, size_t n) {
  out[0] = 0;
  String open = String('<') + tag + '>';
  int a = x.indexOf(open);
  if (a < 0) return;
  a += open.length();
  int b = x.indexOf('<', a);
  if (b < 0) return;
  String v = x.substring(a, b);
  v.trim();
  strlcpy(out, v.c_str(), n);
}

static const char *const BAND_GROUPS[4] = {"80m-40m", "30m-20m", "17m-15m", "12m-10m"};

static bool fetchSolar() {
  String x;
  if (!httpsGet(SOLAR_URL, "Propagation", x)) return false;

  Solar s = {};
  xmlValue(x, "solarflux", s.sfi, sizeof s.sfi);
  xmlValue(x, "sunspots", s.sn, sizeof s.sn);
  xmlValue(x, "aindex", s.a, sizeof s.a);
  xmlValue(x, "kindex", s.k, sizeof s.k);
  xmlValue(x, "xray", s.xray, sizeof s.xray);
  for (int i = 0; i < 4; i++)
    for (int j = 0; j < 2; j++) {
      char key[48];
      snprintf(key, sizeof key, "name=\"%s\" time=\"%s\">", BAND_GROUPS[i], j ? "night" : "day");
      int p = x.indexOf(key);
      if (p < 0) continue;
      p += strlen(key);
      s.cond[i][j] = x.startsWith("Good", p) ? 1 : x.startsWith("Fair", p) ? 2 : x.startsWith("Poor", p) ? 3 : 0;
    }
  if (!s.sfi[0]) return false;
  s.ok = true;
  s.fetchedAt = timeValid() ? time(nullptr) : 0;
  s.fetchedMs = millis();
  lock();
  solar = s;
  unlock();
  static char lastUpdated[32];      // N0NBH refreshes about hourly, we fetch more often
  char updated[32];
  xmlValue(x, "updated", updated, sizeof updated);
  if (strcmp(updated, lastUpdated)) {
    strcpy(lastUpdated, updated);
    propagationSeq++;
  }
  if (!quietLog) Serial.printf("Propagation: SFI %s SN %s A %s K %s X %s\r\n", s.sfi, s.sn, s.a, s.k, s.xray);
  return true;
}

// Number after "key": in KC2G JSON (with spaces); null or missing key → false.
static bool jsonNumber(const String &js, int from, int to, const char *key, float &v) {
  String pat = String('"') + key + "\":";
  int p = js.indexOf(pat, from);
  if (p < 0 || p >= to) return false;
  const char *s = js.c_str() + p + pat.length();
  while (*s == ' ') s++;
  char *end;
  v = strtof(s, &end);
  return end != s;
}

// Text after "key": "value" in KC2G JSON; missing key → false.
static bool jsonText(const String &js, int from, int to, const char *key, char *out, size_t n) {
  String pat = String('"') + key + "\": \"";
  int p = js.indexOf(pat, from);
  if (p < 0 || p >= to) return false;
  p += pat.length();
  int e = js.indexOf('"', p);
  if (e < 0 || e >= to) return false;
  strlcpy(out, js.c_str() + p, min<size_t>(n, e - p + 1));
  return true;
}

// Bounds [from, to) of the next top-level object of a JSON array, searched from pos. KC2G does not keep
// the key order of its records stable (once "source" came first, later "tec"), so records are found
// by their braces, never by their first key.
static bool nextJsonObject(const String &js, int pos, int &from, int &to) {
  const char *s = js.c_str();
  int depth = 0;
  bool inStr = false;
  for (int i = pos, n = js.length(); i < n; i++) {
    char c = s[i];
    if (inStr) {
      if (c == '\\') i++;
      else if (c == '"') inStr = false;
    } else if (c == '"') {
      inStr = true;
    } else if (c == '{') {
      if (!depth++) from = i;
    } else if (c == '}' && depth && !--depth) {
      to = i + 1;
      return true;
    }
  }
  return false;
}

// One KC2G record, keys in any order: {"station": {"code": "PQ052", "name": …, "longitude": "14.6",
// "latitude": "50"}, "time": "2026-10-09T16:40:00", "fof2": 6.0, "mufd": 19.8, "source": "giro", …}.
// Without foF2 or time → false.
static bool parseIonoRecord(const String &js, int from, int to, Iono &io) {
  io = {};
  char lat[12], lon[12], when[24];
  if (!jsonText(js, from, to, "code", io.code, sizeof io.code) || !jsonNumber(js, from, to, "fof2", io.fof2) ||
      !jsonText(js, from, to, "time", when, sizeof when))
    return false;
  int Y, M, D, h, m;
  if (sscanf(when, "%d-%d-%dT%d:%d", &Y, &M, &D, &h, &m) != 5) return false;
  io.measuredAt = (int64_t)daysFromCivil(Y, M, D) * 86400 + h * 3600 + m * 60;   // int32 would overflow in 2038
  jsonNumber(js, from, to, "mufd", io.mufd);
  jsonText(js, from, to, "name", io.name, sizeof io.name);
  if (homeOk && jsonText(js, from, to, "latitude", lat, sizeof lat) && jsonText(js, from, to, "longitude", lon, sizeof lon)) {
    float la = atof(lat), lo = atof(lon);
    if (lo > 180) lo -= 360;          // KC2G has longitude 0–360
    io.km = max(1L, lroundf(distanceKm(homeLat, homeLon, la, lo)));
  }
  io.ok = true;
  return true;
}

// Picks the ionosonde: the one given by code, otherwise the nearest with a fresh measurement within IONO_MAX_KM.
// The current one stays until it is more than IONO_STICKY_KM farther than the nearest, so readings
// do not jump between two stations that drop out alternately.
// false = download failed (retried sooner); with no suitable ionosonde the old data stays until it ages out.
static bool fetchIono() {           // called only with valid time
  String js;
  if (!httpsGet(IONO_URL, "Ionosonde", js)) return false;
  uint32_t now = time(nullptr);
  char last[sizeof iono.code];
  strcpy(last, iono.code);          // iono is written only by this task, so it may read it without the lock
  bool manual = cfg.iono[0], listed = false;
  Iono best = {}, kept = {}, rec;
  for (int from, to, pos = 0; nextJsonObject(js, pos, from, to); pos = to) {
    if (parseIonoRecord(js, from, to, rec)) {
      bool match = manual && !strcmp(rec.code, cfg.iono);
      listed |= match;
      bool fresh = now >= rec.measuredAt && now - rec.measuredAt < IONO_MAX_AGE_MIN * 60u;
      if (fresh && (match || (!manual && rec.km && rec.km <= IONO_MAX_KM))) {
        if (!best.ok || rec.km < best.km) best = rec;
        if (!manual && !strcmp(rec.code, last)) kept = rec;
      }
    }
  }
  if (kept.ok && kept.km <= best.km + IONO_STICKY_KM) best = kept;
  if (!best.ok) {
    if (quietLog) return true;
    if (!manual)      Serial.printf("Ionosonde: none with a fresh measurement within %u km\r\n", IONO_MAX_KM);
    else if (!listed) Serial.printf("Ionosonde %s: not in the data\r\n", cfg.iono);
    else              Serial.printf("Ionosonde %s: no fresh measurement\r\n", cfg.iono);
    return true;
  }
  lock();
  bool changed = !iono.ok || iono.measuredAt != best.measuredAt || strcmp(iono.code, best.code);
  iono = best;
  unlock();
  if (changed) propagationSeq++;
  if (!quietLog) {
    time_t t = best.measuredAt;
    struct tm u;
    gmtime_r(&t, &u);
    Serial.printf("Ionosonde %s (%s, %u km): foF2 %.1f MHz, MUF %.1f MHz (%02d:%02d UTC)\r\n", best.code, best.name,
                  best.km, best.fof2, best.mufd, u.tm_hour, u.tm_min);
  }
  return true;
}

// A measurement is fresh when not older than IONO_MAX_AGE_MIN (trusted without valid time).
static bool ionoFresh(const Iono &io) {
  if (!io.ok) return false;
  if (!timeValid() || !io.measuredAt) return true;
  return (uint32_t)time(nullptr) - io.measuredAt < IONO_MAX_AGE_MIN * 60u;
}

// Recommended NVIS band: the highest band whose lower edge lies below foF2
// reduced by the configured margin (the classic optimum working frequency FOT is 0.85 × foF2).
// Returns e.g. "80", or nullptr when there is no data or foF2 is below 160 m.
static const char *nvisBand(const Iono &io) {
  struct Band { float mhz; const char *name; };
  static const Band BANDS[] = {{14.0f, "20"}, {10.1f, "30"}, {7.0f, "40"}, {5.3515f, "60"}, {3.5f, "80"}, {1.8f, "160"}};
  if (!ionoFresh(io)) return nullptr;
  float limit = io.fof2 * (100 - cfg.nvisMargin) / 100;
  for (const Band &b : BANDS)
    if (b.mhz <= limit && (cfg.nvis60 || strcmp(b.name, "60"))) return b.name;
  return nullptr;
}

// ============================ NETWORK TASK ============================

static void onTimeSync(struct timeval *tv) {   // called by SNTP after each sync (about hourly)
  if (quietLog) return;
  time_t t = tv->tv_sec;
  struct tm u;
  gmtime_r(&t, &u);
  Serial.printf("NTP: time set, %02d:%02d:%02d UTC\r\n", u.tm_hour, u.tm_min, u.tm_sec);
}

// Why connecting fails (from the disconnect event reason code), so the display can say so.
static void onWifiDisconnect(WiFiEvent_t, WiFiEventInfo_t info) {
  uint8_t r = info.wifi_sta_disconnected.reason;
  if (r == WIFI_REASON_ASSOC_LEAVE) return;   // we disconnected ourselves (new attempt), the previous failure reason still holds
  WifiFail f = r == WIFI_REASON_NO_AP_FOUND ? WF_NO_AP
             : r == WIFI_REASON_AUTH_FAIL || r == WIFI_REASON_4WAY_HANDSHAKE_TIMEOUT ||
               r == WIFI_REASON_HANDSHAKE_TIMEOUT || r == WIFI_REASON_AUTH_EXPIRE ? WF_AUTH
             : WF_OTHER;
  if (f != wifiFailSeen && !quietLog)
    Serial.printf("WiFi: cannot connect to %s (%s, code %u)\r\n", cfg.ssid, WIFI_FAIL_LOG[f], r);
  wifiFailSeen = f;
}

// Wait after the n-th failed download in a row: 2 min, then longer each time, up to an hour, so a server
// that is down is not asked every 2 minutes by every board.
static uint32_t retryDelay(uint8_t fails) {
  uint32_t ms = FETCH_RETRY_MIN_MS;
  for (uint8_t i = 1; i < fails && ms < FETCH_RETRY_MAX_MS; i++) ms *= 2;
  return jittered(min<uint32_t>(ms, FETCH_RETRY_MAX_MS));
}

static void netTask(void *) {
  WiFi.onEvent(onWifiDisconnect, ARDUINO_EVENT_WIFI_STA_DISCONNECTED);
  WiFi.mode(WIFI_STA);
  WiFi.setHostname("microhamclock");
  WiFi.setAutoReconnect(true);
  WiFi.begin(cfg.ssid, cfg.pass[0] ? cfg.pass : nullptr);
  bool ntpStarted = false, wasUp = false;
  uint32_t nextSolar = 0, nextIono = 0, nextExpire = 0, lastBegin = millis(), downSince = millis();
  uint8_t solarFails = 0, ionoFails = 0;

  for (;;) {
    uint32_t now = millis();
    bool up = WiFi.status() == WL_CONNECTED;
    if (up != wasUp) {
      wasUp = up;
      if (!up) downSince = now;
      else {                          // the first downloads come soon, but not all at the same moment
        nextSolar = now + esp_random() % START_SPREAD_MS;
        nextIono = now + esp_random() % START_SPREAD_MS;
      }
      if (!quietLog) {
        if (up) Serial.printf("WiFi: connected, IP %s\r\n", WiFi.localIP().toString().c_str());
        else    Serial.println("WiFi: disconnected");
      }
    }
    wifiUp = up;
    if (up) wifiFailSeen = WF_NONE;
    wifiFail = !up && now - downSince >= WIFI_FAIL_SHOW_MS ? wifiFailSeen : WF_NONE;
    if (!up) {
      if (mqttState != MS_IDLE) mqttDrop("Wi-Fi down");
      // The core does not reconnect by itself after some errors (e.g. AUTH_FAIL), so we retry ourselves.
      if (now - lastBegin > WIFI_RETRY_MS) {
        WiFi.disconnect();
        WiFi.begin(cfg.ssid, cfg.pass[0] ? cfg.pass : nullptr);
        lastBegin = now;
      }
      vTaskDelay(pdMS_TO_TICKS(500));
      continue;
    }
    lastBegin = now;
    if (!ntpStarted) {                // time comes from NTP only after connecting to Wi-Fi
      sntp_set_time_sync_notification_cb(onTimeSync);
      configTzTime(tzRule, NTP_1, NTP_2, NTP_3);
      ntpStarted = true;
    }

    mqttService();

    if (solar.ok && !solar.fetchedAt && timeValid()) {   // fetched before NTP: date it now
      lock();
      solar.fetchedAt = time(nullptr) - (millis() - solar.fetchedMs) / 1000;
      unlock();
    }

    if ((int32_t)(now - nextSolar) >= 0) {
      bool ok = fetchSolar();
      solarFails = ok ? 0 : min<uint8_t>(solarFails + 1, 16);
      nextSolar = millis() + (ok ? jittered(SOLAR_REFRESH_MIN * 60000UL) : retryDelay(solarFails));
    }
    if (timeValid() && (int32_t)(now - nextIono) >= 0) {   // without time a fresh measurement cannot be recognized
      bool ok = fetchIono();
      ionoFails = ok ? 0 : min<uint8_t>(ionoFails + 1, 16);
      nextIono = millis() + (ok ? jittered(IONO_REFRESH_MIN * 60000UL) : retryDelay(ionoFails));
    }
    if ((int32_t)(now - nextExpire) >= 0) {
      expireSpots();
      nextExpire = now + 10000;
    }
    vTaskDelay(pdMS_TO_TICKS(20));
  }
}

// ============================ POWER (BATTERY, POWER OFF) ============================
// The battery voltage is measured on GPIO1 through a divider that GPIO37 switches on. Its polarity
// differs between revisions: V3 and V3.1 have a pull-up and are active LOW, V3.2 has a transistor and
// is active HIGH. The pull-up also tells them apart: the pin left as an input reads HIGH only on V3/V3.1.
// Power off = deep sleep with no wake-up source; only the RST button (a full reset) starts the board.

static TaskHandle_t netTaskHandle;
static bool boardV32Detected;
static uint16_t batteryMv;          // last measurement, 0 = not measured yet

static bool boardV32() { return cfg.board == BD_V32 || (cfg.board == BD_AUTO && boardV32Detected); }

static const char *boardName() { return BOARD_NAME[boardV32() ? BD_V32 : BD_V31]; }

// Called at boot before anything drives GPIO37; then the divider stays on (about 9 µA, nothing next to Wi-Fi).
static void batteryInit() {
  gpio_hold_dis(gpio_num_t(PIN_VBAT_CTRL));    // held since a power off when woken by the timer
  pinMode(PIN_VBAT_CTRL, INPUT);
  delayMicroseconds(200);
  boardV32Detected = digitalRead(PIN_VBAT_CTRL) == LOW;
  pinMode(PIN_VBAT_CTRL, OUTPUT);
  digitalWrite(PIN_VBAT_CTRL, boardV32() ? HIGH : LOW);
  delay(2);
}

static uint16_t readBatteryMv() {
  uint32_t sum = 0;
  for (int i = 0; i < 16; i++) sum += analogReadMilliVolts(PIN_VBAT);
  return sum / 16 * VBAT_DIVIDER;
}

static bool batteryPresent(uint16_t mv) { return mv >= BAT_NONE_MV; }

// Rough charge of a Li-ion cell from its voltage under a light load.
static int batteryPercent(uint16_t mv) {
  static const uint16_t MV[] = {3300, 3400, 3500, 3600, 3700, 3800, 3900, 4000, 4100, 4200};
  static const uint8_t PCT[] = {0, 4, 10, 22, 40, 55, 68, 79, 90, 100};
  if (mv <= MV[0]) return 0;
  for (size_t i = 1; i < sizeof MV / sizeof MV[0]; i++)
    if (mv <= MV[i]) return PCT[i - 1] + (PCT[i] - PCT[i - 1]) * (mv - MV[i - 1]) / (MV[i] - MV[i - 1]);
  return 100;
}

// Puts the SX1262 into sleep (SetSleep, cold start); after a power-on it sits in standby.
static void loraSleep() {
  pinMode(PIN_LORA_RST, OUTPUT);
  digitalWrite(PIN_LORA_RST, HIGH);
  pinMode(PIN_LORA_NSS, OUTPUT);
  digitalWrite(PIN_LORA_NSS, HIGH);
  pinMode(PIN_LORA_BUSY, INPUT);
  SPI.begin(PIN_LORA_SCK, PIN_LORA_MISO, PIN_LORA_MOSI, PIN_LORA_NSS);
  for (uint32_t t = millis(); digitalRead(PIN_LORA_BUSY) == HIGH && millis() - t < 20;) delay(1);
  SPI.beginTransaction(SPISettings(2000000, MSBFIRST, SPI_MODE0));
  digitalWrite(PIN_LORA_NSS, LOW);
  SPI.transfer(0x84);               // SetSleep
  SPI.transfer(0x00);               // cold start, RTC timeout off
  digitalWrite(PIN_LORA_NSS, HIGH);
  SPI.endTransaction();
  SPI.end();
  delay(1);
}

static void holdPin(uint8_t pin, bool high) {
  pinMode(pin, OUTPUT);
  digitalWrite(pin, high ? HIGH : LOW);
  gpio_hold_en(gpio_num_t(pin));
}

// Pins held through deep sleep are released at boot (a timer wake keeps the holds).
static void releasePinHolds() {
  for (uint8_t pin : {PIN_VEXT, PIN_VBAT_CTRL, PIN_LORA_NSS, PIN_LORA_RST}) gpio_hold_dis(gpio_num_t(pin));
  gpio_deep_sleep_hold_dis();
}

// Turns everything off and goes to deep sleep. flat = the battery is flat: with BAT_FLAT_RECHECK the board
// then wakes every BAT_RECHECK_MIN to check whether it has been charged, otherwise only RST starts it, as
// after the manual power off. show = say so on the display first.
static void powerOff(bool flat, bool show) {
  if (show) {
    memset(fb, 0, sizeof fb);
    const char *title = tr(flat ? S_BATTERY_FLAT : S_POWER_OFF);
    if (textWidth(title, 2) <= 128) drawTextCenter(title, 14, 2);
    else                            drawTextCenter(title, 18);   // too long for big letters
    drawTextCenter(tr(S_POWER_RST), 40);
    oledPower(true);
    oledContrast(cfg.bright[BR_DAY]);
    oledFlush();
  }
  Serial.println(flat ? "Power off: battery flat" : "Power off: press RST to start again");
  Serial.flush();
  if (show) delay(1500);
  if (netTaskHandle) vTaskSuspend(netTaskHandle);
  WiFi.disconnect(true);
  WiFi.mode(WIFI_OFF);
  digitalWrite(LED_BUILTIN, LOW);
  loraSleep();
  Wire.end();                       // no pull-ups on the I2C lines of the unpowered display
  for (uint8_t pin : {PIN_OLED_SDA, PIN_OLED_SCL, PIN_OLED_RST}) pinMode(pin, INPUT);
  holdPin(PIN_VEXT, true);          // display power off
  holdPin(PIN_VBAT_CTRL, !boardV32());   // battery divider off
  holdPin(PIN_LORA_NSS, true);      // a falling NSS would wake the radio
  holdPin(PIN_LORA_RST, true);
  gpio_deep_sleep_hold_en();
  if (flat && BAT_FLAT_RECHECK) esp_sleep_enable_timer_wakeup(BAT_RECHECK_MIN * 60ULL * 1000000ULL);
  esp_deep_sleep_start();
}

// Factory reset: erases the whole NVS partition (our settings and the Wi-Fi driver's stored network)
// and restarts, so the board comes up in setup mode like a new one.
static void factoryReset() {
  memset(fb, 0, sizeof fb);
  drawTextCenter(tr(S_FACTORY_RESET), 28);
  oledFlush();
  Serial.println("Factory reset: erasing all settings, restarting...");
  Serial.flush();
  if (netTaskHandle) vTaskSuspend(netTaskHandle);
  WiFi.disconnect(true);
  WiFi.mode(WIFI_OFF);
  prefs.end();
  esp_err_t err = nvs_flash_erase();
  if (err != ESP_OK) Serial.printf("Factory reset: erase failed (%s)\r\n", esp_err_to_name(err));
  Serial.flush();
  delay(800);
  ESP.restart();
}

// Measures the battery now and then. With BAT_AUTO_OFF a flat cell powers the board off.
static void batteryService(uint32_t now) {
  static uint32_t lastAt;
  static uint8_t lowCount;
  if (batteryMv && now - lastAt < BAT_CHECK_S * 1000UL) return;
  lastAt = now;
  batteryMv = readBatteryMv();
  if (!BAT_AUTO_OFF) return;
  lowCount = batteryPresent(batteryMv) && batteryMv < BAT_OFF_MV ? lowCount + 1 : 0;
  if (lowCount >= BAT_OFF_COUNT) powerOff(true, true);
}

// After a power off for a flat battery the timer wakes the board (BAT_FLAT_RECHECK): back to sleep unless it
// was charged.
static void batteryBootCheck() {
  if (!BAT_AUTO_OFF || !BAT_FLAT_RECHECK || esp_sleep_get_wakeup_cause() != ESP_SLEEP_WAKEUP_TIMER) return;
  uint16_t mv = readBatteryMv();
  if (batteryPresent(mv) && mv < BAT_ON_MV) powerOff(true, false);
}

