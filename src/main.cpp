static bool findGlyph(char c, const FontSheet *&sheet, int &col) {
  for (const FontSheet &sh : FONT) {
    const char *hit = strchr(sh.chars, c);
    if (!hit) continue;
    sheet = &sh;
    col = (hit - sh.chars) * 6;
    return true;
  }
  return false;
}

// Draws one line of text; scale = magnification (2 → 10×14 px glyph),
// on = false draws in black (text on a light background).
// A char is looked up exactly, and if the font lacks it, its uppercase form.
// So draw user data (locator, SSID) through upperCopy().
static void drawText(const char *s, int x, int y, int scale = 1, bool on = true) {
  for (; *s && *s != '\n'; s++, x += 6 * scale) {
    const FontSheet *sheet;
    int col;
    if (!findGlyph(*s, sheet, col) && !findGlyph(toupper((unsigned char)*s), sheet, col)) continue;
    for (int r = 0; r < 7; r++)
      for (int i = 0; i < 5; i++)
        if (sheet->rows[r][col + i] == '#') fillRect(x + i * scale, y + r * scale, scale, scale, on);
  }
}

static const char *upperCopy(const char *s, char *out, size_t n) {
  size_t i = 0;
  for (; s[i] && i + 1 < n; i++) out[i] = toupper((unsigned char)s[i]);
  out[i] = 0;
  return out;
}

static int textWidth(const char *s, int scale = 1) {
  int n = strlen(s);
  return n > 0 ? (n * 6 - 1) * scale : 0;
}

static void drawTextRight(const char *s, int right, int y, int scale = 1, bool on = true) {
  drawText(s, right - textWidth(s, scale) + 1, y, scale, on);
}

static void drawTextCenter(const char *s, int y, int scale = 1) {
  drawText(s, (128 - textWidth(s, scale)) / 2, y, scale);
}

