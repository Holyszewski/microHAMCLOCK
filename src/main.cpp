// Network list for the form's script: {"scanning":…,"nets":[{"s":ssid,"r":rssi,"o":open},…]}.
// ?scan=1 starts a new scan first.
static void handleNets() {
  portalSeenAt = millis();
  if (web.hasArg("scan")) startScan();
  String j;
  j.reserve(40 + netCount * 60);
  j += scanRunning ? "{\"scanning\":true,\"nets\":[" : "{\"scanning\":false,\"nets\":[";
  for (int i = 0; i < netCount; i++) {
    if (i) j += ',';
    j += "{\"s\":" + jsonString(nets[i].ssid.c_str()) + ",\"r\":" + nets[i].rssi + ",\"o\":" +
         (nets[i].open ? "true}" : "false}");
  }
  j += "]}";
  web.sendHeader("Cache-Control", "no-store");
  web.send(200, "application/json", j);
}

static int codeIndex(const String &code, const char *const *codes, int n) {
  for (int i = 0; i < n; i++)
    if (code == codes[i]) return i;
  return -1;
}

// Basic settings, shared by the hotspot form and the web installer. Copies the values into d
// (also wrong ones, so they need not be retyped after an error) and returns an error text ID,
// or -1 when all is fine; then d also holds the password and the normalized callsign and locator.
static int checkBasic(Config &d, String ssid, const String &pass, bool open, String call, String loc,
                      const String &tz) {
  ssid.trim();
  call.trim();
  loc.trim();
  strlcpy(d.ssid, ssid.c_str(), sizeof d.ssid);
  strlcpy(d.call, call.c_str(), sizeof d.call);
  strlcpy(d.loc, loc.c_str(), sizeof d.loc);
  char tzId[sizeof d.tz];
  bool tzOk = tzPosix(tz.c_str(), tzId, sizeof tzId);
  if (tzOk) strlcpy(d.tz, tzId, sizeof d.tz);
  char callBuf[16], locBuf[8];
  strlcpy(callBuf, call.c_str(), sizeof callBuf);
  strlcpy(locBuf, loc.c_str(), sizeof locBuf);
  if (!ssid.length() || ssid.length() > 32) return W_ERR_SSID;
  if (!open && pass.length() && (pass.length() < 8 || pass.length() > 63)) return W_ERR_PASS_LEN;
  if (!open && !pass.length() && ssid != cfg.ssid) return W_ERR_PASS_NEW;
  if (call.length() > 11 || !normalizeCall(callBuf)) return W_ERR_CALL;
  if (loc.length() > 6 || !normalizeLocator(locBuf)) return W_ERR_LOC;
  if (!tzOk) return W_ERR_TZ;
  if (open) d.pass[0] = 0;
  else if (pass.length()) strlcpy(d.pass, pass.c_str(), sizeof d.pass);
  strlcpy(d.call, callBuf, sizeof d.call);
  strlcpy(d.loc, locBuf, sizeof d.loc);
  return -1;
}

static void handleSave() {
  portalSeenAt = millis();
  Lang lang = requestLang();
  String svmin = web.arg("svmin");
  svmin.trim();

  // d = what the user entered (even if wrong, so it need not be retyped after an error)
  Config d = cfg;
  strlcpy(d.lang, langInfo(lang).code, sizeof d.lang);
  long minutes = svmin.toInt();
  bool minOk = svmin.length() && svmin.length() <= 3 && minutes >= 0 && minutes <= MAX_SAVER_MIN;
  for (size_t i = 0; i < svmin.length(); i++) minOk &= isdigit((unsigned char)svmin[i]) != 0;
  if (minOk) d.saverMin = minutes;
  int mode = codeIndex(web.arg("svmode"), SAVER_CODE, SV_MODE_COUNT);
  if (mode >= 0) d.saverMode = mode;
  d.wakeOnSpot = web.hasArg("svspot");
  d.ledOnSpotWake = web.hasArg("svled");
  d.lifeOff = web.hasArg("lfoff");
  String lfdays = web.arg("lfdays");
  lfdays.trim();
  long days = lfdays.toInt();
  bool daysOk = lfdays.length() && days >= 1 && days <= MAX_LIFE_DAYS;
  if (daysOk) d.lifeDays = days;
  if (!d.lifeOff) daysOk = true;      // ignored while unticked, the stored number stays
  d.rotate = web.hasArg("rotate");
  long rotsec = web.arg("rotsec").toInt();
  if (rotsec >= MIN_ROTATE_S && rotsec <= MAX_ROTATE_S) d.rotateSec = rotsec;
  d.rotateAll = web.hasArg("rotall");
  d.rotateMap = web.hasArg("rotmap");
  long nf = web.arg("nfrom").toInt(), nt = web.arg("nto").toInt();
  if (nf >= 0 && nf < 24) d.nightFrom = nf;
  if (nt >= 0 && nt < 24) d.nightTo = nt;
  int nmode = codeIndex(web.arg("nmode"), NIGHT_CODE, NM_MODE_COUNT);
  if (nmode >= 0) d.nightMode = nmode;
  for (int i = 0; i < BR_COUNT; i++) {
    long pct = web.arg(BRIGHT_KEY[i]).toInt();
    if (pct >= 1 && pct <= 100) d.bright[i] = pctToContrast(pct);
  }
  String nvismg = web.arg("nvismg");
  nvismg.trim();
  long margin = nvismg.toInt();
  if (nvismg.length() && margin >= 0 && margin <= MAX_NVIS_MARGIN) d.nvisMargin = margin;
  d.nvis60 = web.hasArg("nvis60");
  String ionoArg = web.arg("iono");   // GIRO ionosonde code: letters, digits, underscore (e.g. NI63_)
  ionoArg.trim();
  ionoArg.toUpperCase();
  bool ionoOk = ionoArg.length() < sizeof d.iono;
  for (size_t i = 0; i < ionoArg.length(); i++) ionoOk &= isalnum((unsigned char)ionoArg[i]) || ionoArg[i] == '_';
  strlcpy(d.iono, ionoArg.c_str(), sizeof d.iono);
  d.mapCz = web.hasArg("mapcz");
  d.mapDe = web.hasArg("mapde");
  d.mapUs = web.hasArg("mapus");
  d.mapUk = web.hasArg("mapuk");
  int board = codeIndex(web.arg("board"), BOARD_CODE, BD_COUNT);
  if (board >= 0) d.board = board;

  int err = checkBasic(d, web.arg("ssid"), web.arg("pass"), web.hasArg("open"), web.arg("call"), web.arg("loc"),
                       web.arg("tz"));
  if (err < 0) err = !minOk ? W_ERR_SAVER : !daysOk ? W_ERR_LIFE_DAYS : !ionoOk ? W_ERR_IONO : -1;
  if (err >= 0) {
    sendForm(lang, tr(StrId(err), lang), d, false);
    return;
  }
  saveConfig(d);
  Serial.printf("Hotspot: saved (%s, %s, %s, %s, %s), restarting\r\n", d.ssid, d.call, d.loc, d.lang, d.tz);
  char msg[400];
  snprintf(msg, sizeof msg, tr(W_SAVED, lang), htmlEscape(d.ssid).c_str());
  sendPage(lang, String("<p>") + msg + "</p>");
  restartSoon(1500);
}

