/*
  microHAMCLOCK for the Heltec WiFi LoRa 32 V3
  ---------------------------------------
  ESP32-S3 + 0.96" SSD1306 128×64 OLED (I2C) + Wi-Fi.
  A PlatformIO project (see platformio.ini), needs no extra
  libraries.

  Screens:
    CLOCK       – UTC in big digits, local time, callsign and locator
    PROPAGATION – SFI, SN, A, K, X-ray and band conditions (N0NBH, hamqsl.com)
    PSK LIST    – who heard me in the last hour (PSKReporter via MQTT)
    PSK MAP     – the same on a world map with the grey line (day/night)

  PRG button:
    short press   – next screen
    double click  – automatic screen rotation on/off
    triple click  – status screen (Wi-Fi, MQTT, data)
    long press    – (after holding 0.7 s) list: sort by time / distance
                    map: view AUTO → WORLD → EUROPE → CZECHIA
    hold 10 s     – setup mode (hotspot), works even while waiting for Wi-Fi

  Settings (language, Wi-Fi, callsign, locator) can be entered in two ways:
    – via the hotspot: the board creates an open Wi-Fi MICROHAMCLOCK-xxxx with a form
      at http://4.3.2.1 (by itself only while unconfigured, otherwise by holding
      the button; stored values are not erased),
    – via the serial console at 115200 Bd with the "setup" command; the board asks for everything.
  Everything is stored in NVS. The "status" command prints what is going on.

  The display and web are in English (default) or Czech, texts are in src/lang/*.inc
  (see i18n.h). The serial console is English only.
*/

