static void wizInput(char *in) {
  trim(in);
  if (!strcasecmp(in, "cancel") || !strcasecmp(in, "zrusit")) {
    Serial.println("Cancelled, nothing was saved.");
    wizEnd();
    return;
  }
  bool keep = !in[0], ok = true;
  switch (wiz) {
    case WZ_LANG:
      if (!keep) {
        Lang l;
        ok = langFromCode(in, l);
        if (ok) strlcpy(draft.lang, langInfo(l).code, sizeof draft.lang);
        else {
          char codes[32];
          langCodes(codes, sizeof codes);
          Serial.printf("Unknown language, choose one of: %s\n", codes);
        }
      }
      break;
    case WZ_SSID:
      if (!keep) strlcpy(draft.ssid, in, sizeof draft.ssid);
      ok = draft.ssid[0];
      if (!ok) Serial.println("Wi-Fi is required, enter the network name.");
      break;
    case WZ_PASS:
      if (!strcmp(in, "-")) {
        draft.pass[0] = 0;
      } else if (!keep) {
        ok = strlen(in) >= 8 && strlen(in) <= 63;           // WPA2 accepts no other length
        if (ok) strlcpy(draft.pass, in, sizeof draft.pass);
        else Serial.println("A Wi-Fi password has 8 to 63 characters.");
      }
      break;
    case WZ_CALL:
      if (!keep) strlcpy(draft.call, in, sizeof draft.call);
      ok = normalizeCall(draft.call);
      if (!ok) {
        Serial.println("A callsign has 3-11 characters: letters, digits and slash.");
        strlcpy(draft.call, cfg.call, sizeof draft.call);
      }
      break;
    case WZ_LOC:
      if (!keep) {
        if (strlen(in) < sizeof draft.loc) strlcpy(draft.loc, in, sizeof draft.loc);
        else ok = false;
      }
      ok = ok && normalizeLocator(draft.loc);
      if (!ok) {
        Serial.println("A locator looks like JO70 or JO70va.");
        strlcpy(draft.loc, cfg.loc, sizeof draft.loc);
      }
      break;
    case WZ_TZ:
      if (!keep) {
        if (!strcasecmp(in, "list")) {
          for (size_t i = 0; i < tzZoneCount(); i++) {
            char label[96];
            tzLabel(tzZone(i), label, sizeof label);
            Serial.printf("  %-22s %s\n", tzZone(i).id, label);
          }
          Serial.printf("  or a fixed offset UTC%+d ... UTC%+d (no daylight saving time)\n", TZ_FIXED_MIN, TZ_FIXED_MAX);
          ok = false;
          break;
        }
        char id[sizeof draft.tz];
        int found = tzSearch(in, id, sizeof id);
        if (found == 1) {
          strlcpy(draft.tz, id, sizeof draft.tz);
          Serial.printf("Time zone: %s\n", draft.tz);
        } else if (found > 1) {
          Serial.println("More time zones match, be more specific:");
          tzSearch(in, nullptr, 0, [](const char *zid, const char *cities) { Serial.printf("  %-22s %s\n", zid, cities); });
          ok = false;
        } else {
          Serial.println("Unknown time zone. Type a city, a UTC offset like UTC+3, or 'list'.");
          ok = false;
        }
      }
      break;
    case WZ_SAVER_MIN:
      if (!keep) {
        char *end;
        long m = strtol(in, &end, 10);
        ok = !*end && m >= 0 && m <= MAX_SAVER_MIN;
        if (ok) draft.saverMin = m;
        else Serial.printf("Enter 0 to %u minutes.\n", MAX_SAVER_MIN);
      }
      break;
    case WZ_SAVER_MODE:
      if (!keep) {
        int m = -1;
        for (int i = 0; i < SV_MODE_COUNT; i++) if (!strcasecmp(in, SAVER_CODE[i])) m = i;
        ok = m >= 0;
        if (ok) draft.saverMode = m;
        else Serial.println("Type off, life or dim.");
      }
      break;
    case WZ_WAKE_SPOT:
    case WZ_WAKE_LED:
      if (!keep) {
        char c = tolower((unsigned char)in[0]);
        ok = c == 'y' || c == 'a' || c == 'n';
        if (ok) {
          if (wiz == WZ_WAKE_SPOT) draft.wakeOnSpot = c != 'n';
          else draft.ledOnSpotWake = c != 'n';
        }
        else Serial.println("Type y or n.");
      }
      break;
    case WZ_NIGHT:
      if (!keep) {
        int from, to;
        char extra;
        ok = sscanf(in, "%d-%d%c", &from, &to, &extra) == 2 && from >= 0 && from < 24 && to >= 0 && to < 24;
        if (ok) {
          draft.nightFrom = from;
          draft.nightTo = to;
        } else {
          Serial.println("Type two hours 0-23, e.g. 22-6.");
        }
      }
      break;
    case WZ_NIGHT_MODE:
      if (!keep) {
        int m = -1;
        for (int i = 0; i < NM_MODE_COUNT; i++) if (!strcasecmp(in, NIGHT_CODE[i])) m = i;
        ok = m >= 0;
        if (ok) draft.nightMode = m;
        else Serial.println("Type button, spots or dark.");
      }
      break;
    case WZ_CONFIRM: {
      char c = tolower((unsigned char)in[0]);
      if (c == 'y' || c == 'a') {                          // "a" = Czech "ano" (yes), so old habits still work
        saveConfig(draft);
        Serial.println("Saved, restarting...");
        Serial.flush();
        delay(300);
        ESP.restart();
      } else if (c == 'n') {
        Serial.println("Nothing was saved.");
        wizEnd();
        return;
      }
      ok = false;
      break;
    }
    default: break;
  }
  if (ok) wiz = WizStep(wiz + 1);
  wizPrompt();
}

