static uint8_t fb[128 * 64 / 8];   // frame: 8 pages of 128 bytes, 1 bit = 1 pixel

static void oledCommands(const uint8_t *cmd, size_t len) {
  Wire.beginTransmission(OLED_ADDR);
  Wire.write(0x00);                 // commands follow
  Wire.write(cmd, len);
  Wire.endTransmission();
}

static void oledInit() {
  pinMode(PIN_VEXT, OUTPUT);
  digitalWrite(PIN_VEXT, LOW);
  delay(50);
  pinMode(PIN_OLED_RST, OUTPUT);
  digitalWrite(PIN_OLED_RST, LOW);
  delay(20);
  digitalWrite(PIN_OLED_RST, HIGH);
  delay(20);

  Wire.begin(PIN_OLED_SDA, PIN_OLED_SCL, I2C_HZ);
  const uint8_t init[] = {
    0xAE,                           // display off
    0xD5, 0x80,                     // clock
    0xA8, 0x3F,                     // 64 rows
    0xD3, 0x00,                     // no vertical offset
    0x40,                           // start at row 0
    0x8D, 0x14,                     // charge pump on
    0x20, 0x00,                     // horizontal addressing
    FLIP_SCREEN ? 0xA0 : 0xA1,      // column direction
    FLIP_SCREEN ? 0xC0 : 0xC8,      // row direction
    0xDA, 0x12,                     // COM pin wiring for 128×64
    0x81, CONTRAST_DAY,
    0xD9, 0xF1,                     // pre-charge
    0xDB, 0x40,                     // VCOMH
    0xA4,                           // display RAM contents
    0xA6,                           // not inverted
    0x2E,                           // no scrolling
    0xAF,                           // display on
  };
  oledCommands(init, sizeof init);
}

static void oledContrast(uint8_t c) {
  const uint8_t cmd[] = {0x81, c};
  oledCommands(cmd, sizeof cmd);
}

// A switched-off display does not light at all (no burn-in) and draws almost no current.
static void oledPower(bool on) {
  static const uint8_t cmdOn[] = {0x8D, 0x14, 0xAF}, cmdOff[] = {0xAE, 0x8D, 0x10};
  oledCommands(on ? cmdOn : cmdOff, 3);
}

static void oledFlush() {
  static const uint8_t window[] = {0x21, 0, 127, 0x22, 0, 7};
  oledCommands(window, sizeof window);
  for (size_t i = 0; i < sizeof fb; i += 64) {
    Wire.beginTransmission(OLED_ADDR);
    Wire.write(0x40);               // data follows
    Wire.write(fb + i, 64);
    Wire.endTransmission();
  }
}

static void setPixel(int x, int y, bool on = true) {
  if ((unsigned)x >= 128 || (unsigned)y >= 64) return;
  uint8_t mask = 1 << (y & 7);
  if (on) fb[(y >> 3) * 128 + x] |= mask;
  else    fb[(y >> 3) * 128 + x] &= ~mask;
}

static void fillRect(int x, int y, int w, int h, bool on = true) {
  for (int j = 0; j < h; j++)
    for (int i = 0; i < w; i++) setPixel(x + i, y + j, on);
}

static void hLine(int x, int y, int w) { fillRect(x, y, w, 1); }

