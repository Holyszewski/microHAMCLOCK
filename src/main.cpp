// ---- custom DNS: answers every name with the hotspot address ----
// Type A (IPv4) queries get the hotspot address, others (mainly AAAA) an empty
// answer without error. Unlike the DNSServer library it also handles queries with EDNS.

static WiFiUDP dnsUdp;

static void dnsService() {
  int len = dnsUdp.parsePacket();
  if (len <= 0) return;
  uint8_t q[512], r[512 + 16];
  if (len > (int)sizeof q || len < 12) {
    dnsUdp.flush();
    return;
  }
  dnsUdp.read(q, len);
  if ((q[2] & 0x80) || (q[4] << 8 | q[5]) != 1) return;   // only queries with a single question

  char name[64];
  int p = 12, n = 0;
  while (p < len && q[p]) {
    int l = q[p++];
    if ((l & 0xC0) || p + l > len) return;
    for (int i = 0; i < l; i++, p++) if (n < (int)sizeof name - 2) name[n++] = q[p];
    name[n++] = '.';
  }
  if (n) n--;
  name[n] = 0;
  p++;                                                     // null terminator of the name
  if (p + 4 > len) return;
  uint16_t qtype = q[p] << 8 | q[p + 1];
  p += 4;                                                  // type and class

  memcpy(r, q, p);                                         // header and question copied back
  r[2] = 0x84 | (q[2] & 0x01);                             // response, authoritative, RD as in the query
  r[3] = 0x80;                                             // RA, no error
  r[6] = r[7] = r[8] = r[9] = r[10] = r[11] = 0;
  int out = p;
  if (qtype == 1 || qtype == 255) {                        // A or ANY
    static const uint8_t ans[] = {0xC0, 0x0C, 0, 1, 0, 1, 0, 0, 0, 10, 0, 4};   // TTL 10 s
    memcpy(r + out, ans, sizeof ans);
    out += sizeof ans;
    IPAddress ip = WiFi.softAPIP();
    for (int i = 0; i < 4; i++) r[out++] = ip[i];
    r[7] = 1;
  }
  dnsUdp.beginPacket(dnsUdp.remoteIP(), dnsUdp.remotePort());
  dnsUdp.write(r, out);
  dnsUdp.endPacket();
}

